class _PolicyTitle extends StatelessWidget {
  const _PolicyTitle(this.text);

  final String text;

  @override
  Widget build(BuildContext context) {
    return MyText(
      text: text,
      size: 20,
      weight: FontWeight.w800,
      color: kTertiaryColor,
      lineHeight: 1.2,
      paddingBottom: 16,
    );
  }
}

class _PolicySection extends StatelessWidget {
  const _PolicySection({required this.title, required this.paragraphs});

  final String title;
  final List<String> paragraphs;

  @override
  Widget build(BuildContext context) {
    return Padding(
      padding: const EdgeInsets.only(bottom: 14),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          MyText(
            text: title,
            size: 15,
            weight: FontWeight.w700,
            color: kTertiaryColor,
            lineHeight: 1.3,
            paddingBottom: 8,
          ),
          for (final paragraph in paragraphs)
            _PolicyParagraph(paragraph, paddingBottom: 8),
        ],
      ),
    );
  }
}

class _PolicyParagraph extends StatelessWidget {
  const _PolicyParagraph(this.text, {this.paddingBottom = 12});

  final String text;
  final double paddingBottom;

  @override
  Widget build(BuildContext context) {
    return MyText(
      text: text,
      size: 13,
      weight: FontWeight.w500,
      color: kGreyColor,
      lineHeight: 1.45,
      paddingBottom: paddingBottom,
    );
  }
}
